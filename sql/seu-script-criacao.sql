-- Sprint 01: EquipeManutencao
CREATE TABLE EQUIPE_MANUTENCAO (
    ID                      NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    NOME_EQUIPE             VARCHAR2(100) NOT NULL,
    QUANTIDADE_FUNCIONARIOS NUMBER NOT NULL,
    REGIAO_ATENDIMENTO      VARCHAR2(100) NOT NULL
);

-- Sprint 02: TrechoRodovia
CREATE TABLE TRECHO_RODOVIA (
    ID               NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    KM_INICIAL       NUMBER NOT NULL,
    KM_FINAL         NUMBER NOT NULL,
    NIVEL_VEGETACAO  NUMBER(6,2) NOT NULL
);

-- Sprint 02: IntervencaoOperacional — Pulverizacao / RocadaMecanizada
-- TIPO_SERVICO funciona como discriminador de qual subclasse reconstruir
CREATE TABLE INTERVENCAO_OPERACIONAL (
    ID             NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    TRECHO_ID      NUMBER NOT NULL,
    TIPO_SERVICO   VARCHAR2(30) NOT NULL,
    DATA_EXECUCAO  DATE DEFAULT SYSDATE NOT NULL,
    OBSERVACOES    VARCHAR2(255),
    CONSTRAINT FK_INTERVENCAO_TRECHO FOREIGN KEY (TRECHO_ID) REFERENCES TRECHO_RODOVIA (ID),
    CONSTRAINT CK_TIPO_SERVICO CHECK (TIPO_SERVICO IN ('ROCADA_MECANIZADA', 'PULVERIZACAO'))
);

-- Entidade nova: RelatorioPrioridade — histórico do que hoje o GeradorRelatorio só imprimia
CREATE TABLE RELATORIO_PRIORIDADE (
    ID            NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    DATA_GERACAO  DATE DEFAULT SYSDATE NOT NULL,
    QTD_ALTA      NUMBER DEFAULT 0 NOT NULL,
    QTD_MEDIA     NUMBER DEFAULT 0 NOT NULL,
    QTD_BAIXA     NUMBER DEFAULT 0 NOT NULL,
    RESUMO        VARCHAR2(500)
);
